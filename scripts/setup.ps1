# ==============================================================================
# FaceCheck Banking KYC Biometrics - Windows PowerShell One-Command Setup
# ==============================================================================
$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$rootDir = Split-Path -Parent $scriptDir
Set-Location $rootDir

Write-Host "==========================================================================" -ForegroundColor Cyan
Write-Host "          FaceCheck Banking KYC Biometrics - Local Setup (PowerShell)" -ForegroundColor Cyan
Write-Host "==========================================================================" -ForegroundColor Cyan

# 1. Verify Docker
Write-Host "[1/7] Checking Docker availability..." -ForegroundColor Yellow
$dockerCheck = docker info 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Error "Docker daemon is not running. Please start Docker Desktop."
    exit 1
}
Write-Host "  Docker daemon is healthy." -ForegroundColor Green

# 2. Cryptographic Secret Generation
Write-Host "[2/7] Checking / generating cryptographic credentials..." -ForegroundColor Yellow
$envFile = Join-Path $rootDir ".env"

function Generate-RandomHex([int]$bytes) {
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $buf = New-Object byte[] $bytes
    $rng.GetBytes($buf)
    return -join ($buf | ForEach-Object { "{0:x2}" -f $_ })
}

if (-not (Test-Path $envFile) -or -not (Select-String -Path $envFile -Pattern "POSTGRES_PASSWORD=" -Quiet) -or (Select-String -Path $envFile -Pattern "CHANGE_ME" -Quiet)) {
    Write-Host "  Generating new high-entropy secrets for all database roles and keys..." -ForegroundColor Cyan
    $pgPass = Generate-RandomHex 24
    $migratorPass = Generate-RandomHex 24
    $appPass = Generate-RandomHex 24
    $workerPass = Generate-RandomHex 24
    $readonlyPass = Generate-RandomHex 24
    $apiKey = "fc-live-" + (Generate-RandomHex 24)
    $encKey = Generate-RandomHex 32
    $hmacKey = Generate-RandomHex 32

    $envContent = @"
# Generated by scripts/setup.ps1 on $(Get-Date -Format "yyyy-MM-ddTHH:mm:ssZ")
# Strictly confidential - Never commit to source control
ENV=development

POSTGRES_DB=facecheck_db
POSTGRES_USER=postgres
POSTGRES_PASSWORD=$pgPass

DB_MIGRATOR_PASSWORD=$migratorPass
DB_APP_PASSWORD=$appPass
DB_ML_WORKER_PASSWORD=$workerPass
DB_READONLY_PASSWORD=$readonlyPass

FACECHECK_API_KEY=$apiKey
ENCRYPTION_MASTER_KEY=$encKey
AUDIT_HMAC_KEY=$hmacKey

FACECHECK_SERVER_HOST=0.0.0.0
FACECHECK_SERVER_PORT=8000

LLM_PROVIDER=ollama
LLM_MODEL=llama3.2
LLM_BASE_URL=http://ollama:11434/v1
CLOUD_LLM_ENABLED=false
DATA_RESIDENCY_APPROVED=false
"@
    Set-Content -Path $envFile -Value $envContent -Encoding UTF8
    Write-Host "  Generated new unique secrets saved to .env." -ForegroundColor Green
} else {
    Write-Host "  Existing valid .env credentials verified." -ForegroundColor Green
}

# 3. Build Images
Write-Host "[3/7] Building multi-stage container images..." -ForegroundColor Yellow
docker compose build
if ($LASTEXITCODE -ne 0) { exit 1 }

# 4. Start Stack
Write-Host "[4/7] Starting services in detached mode..." -ForegroundColor Yellow
docker compose up -d
if ($LASTEXITCODE -ne 0) { exit 1 }

# 5. Wait for Health
Write-Host "[5/7] Waiting for all container healthchecks to pass..." -ForegroundColor Yellow
$services = @("postgres", "ollama", "api", "monitor-web", "ml-worker")
foreach ($svc in $services) {
    Write-Host -NoNewline "  Waiting for $svc to become healthy..."
    $healthy = $false
    for ($i = 0; $i -lt 45; $i++) {
        $status = docker compose ps --format "{{.Health}}" $svc 2>$null
        if ($status -like "*healthy*") {
            $healthy = $true
            break
        }
        Start-Sleep -Seconds 2
        Write-Host -NoNewline "."
    }
    if ($healthy) {
        Write-Host " OK" -ForegroundColor Green
    } else {
        Write-Host " TIMEOUT!" -ForegroundColor Red
        docker compose logs $svc
        exit 1
    }
}

# 6. Apply Migrations
Write-Host "[6/7] Applying database migrations..." -ForegroundColor Yellow
& "$rootDir\scripts\migrate.ps1"
if ($LASTEXITCODE -ne 0) { exit 1 }

# 7. Pull Ollama model
Write-Host "[7/7] Checking local Ollama model (llama3.2)..." -ForegroundColor Yellow
$modelList = docker compose exec -T ollama ollama list 2>$null
if ($modelList -like "*llama3.2*") {
    Write-Host "  Ollama model 'llama3.2' is already present." -ForegroundColor Green
} else {
    Write-Host "  Pulling model 'llama3.2' into Ollama container..." -ForegroundColor Cyan
    $null = docker compose exec -T ollama ollama pull llama3.2 2>&1
    if ($LASTEXITCODE -ne 0) {
        Write-Host "  [NOTE] Ollama model download skipped or offline. Fallback deterministic reasoner active." -ForegroundColor Yellow
    }
}

Write-Host "==========================================================================" -ForegroundColor Green
Write-Host "          FaceCheck Local Stack Successfully Initialized!" -ForegroundColor Green
Write-Host "==========================================================================" -ForegroundColor Green
Write-Host "  * REST API (FastAPI):          http://127.0.0.1:8000/docs"
Write-Host "  * Read-Only Monitor Web:       http://127.0.0.1:8080"
Write-Host "  * Ollama Local LLM:            http://127.0.0.1:11434"
Write-Host "=========================================================================="
