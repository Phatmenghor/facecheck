#!/usr/bin/env bash
# ==============================================================================
# FaceCheck Banking KYC Biometrics - Complete One-Command Local Docker Setup
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

cd "${ROOT_DIR}"

echo "=========================================================================="
echo "          FaceCheck Banking KYC Biometrics - Local Setup"
echo "=========================================================================="

# 1. Verify Docker and Docker Compose
echo "[1/7] Checking Docker and Docker Compose availability..."
if ! command -v docker >/dev/null 2>&1; then
    echo "ERROR: Docker CLI is not installed or not in PATH." >&2
    exit 1
fi

if ! docker info >/dev/null 2>&1; then
    echo "ERROR: Docker daemon is not running. Please start Docker Desktop." >&2
    exit 1
fi

echo "  Docker daemon is healthy (v$(docker version --format '{{.Server.Version}}' 2>/dev/null || echo 'running'))."

# 2. Cryptographic Secret Generation
echo "[2/7] Checking / generating cryptographic credentials..."
ENV_FILE="${ROOT_DIR}/.env"

generate_random_hex() {
    local bytes="$1"
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex "${bytes}"
    else
        python -c "import secrets; print(secrets.token_hex(${bytes}))"
    fi
}

if [[ ! -f "${ENV_FILE}" ]] || ! grep -q "POSTGRES_PASSWORD=" "${ENV_FILE}" 2>/dev/null || grep -q "CHANGE_ME" "${ENV_FILE}" 2>/dev/null; then
    echo "  Generating new high-entropy secrets for all database roles and keys..."
    PG_PASS="$(generate_random_hex 24)"
    MIGRATOR_PASS="$(generate_random_hex 24)"
    APP_PASS="$(generate_random_hex 24)"
    WORKER_PASS="$(generate_random_hex 24)"
    READONLY_PASS="$(generate_random_hex 24)"
    API_KEY="fc-live-$(generate_random_hex 24)"
    ENC_KEY="$(generate_random_hex 32)"
    HMAC_KEY="$(generate_random_hex 32)"

    cat > "${ENV_FILE}" <<EOF
# Generated by scripts/setup.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Strictly confidential - Never commit to source control
ENV=development

POSTGRES_DB=facecheck_db
POSTGRES_USER=postgres
POSTGRES_PASSWORD=${PG_PASS}

DB_MIGRATOR_PASSWORD=${MIGRATOR_PASS}
DB_APP_PASSWORD=${APP_PASS}
DB_ML_WORKER_PASSWORD=${WORKER_PASS}
DB_READONLY_PASSWORD=${READONLY_PASS}

FACECHECK_API_KEY=${API_KEY}
ENCRYPTION_MASTER_KEY=${ENC_KEY}
AUDIT_HMAC_KEY=${HMAC_KEY}

FACECHECK_SERVER_HOST=0.0.0.0
FACECHECK_SERVER_PORT=8000

LLM_PROVIDER=ollama
LLM_MODEL=llama3.2
LLM_BASE_URL=http://ollama:11434/v1
CLOUD_LLM_ENABLED=false
DATA_RESIDENCY_APPROVED=false
EOF
    chmod 600 "${ENV_FILE}" 2>/dev/null || true
    echo "  Generated new unique secrets saved to .env."
else
    echo "  Existing valid .env credentials verified."
fi

# 3. Build Container Images
echo "[3/7] Building multi-stage container images (api, ml-worker, monitor-web)..."
docker compose build

# 4. Start Docker Compose Stack
echo "[4/7] Starting services in detached mode..."
docker compose up -d

# 5. Wait for Service Health
echo "[5/7] Waiting for all container healthchecks to pass..."
MAX_WAIT=90
ELAPSED=0

check_service_health() {
    local service="$1"
    local status
    status="$(docker compose ps --format '{{.Health}}' "${service}" 2>/dev/null || echo "")"
    if [[ "${status}" == *"healthy"* ]]; then
        return 0
    fi
    return 1
}

for svc in postgres ollama api monitor-web ml-worker; do
    echo -n "  Waiting for ${svc} to become healthy..."
    while ! check_service_health "${svc}"; do
        sleep 2
        ELAPSED=$((ELAPSED + 2))
        if [[ ${ELAPSED} -ge ${MAX_WAIT} ]]; then
            echo " TIMEOUT!"
            echo "ERROR: Service ${svc} failed to become healthy within ${MAX_WAIT}s." >&2
            docker compose logs "${svc}"
            exit 1
        fi
        echo -n "."
    done
    echo " OK"
done

# 6. Apply Database Migrations
echo "[6/7] Verifying and applying database migrations..."
"${SCRIPT_DIR}/migrate.sh"

# 7. Pull Ollama Model (Best effort offline)
echo "[7/7] Checking local Ollama model (llama3.2)..."
if docker compose exec -T ollama ollama list | grep -q "llama3.2" 2>/dev/null; then
    echo "  Ollama model 'llama3.2' is already present."
else
    echo "  Pulling model 'llama3.2' into local Ollama container..."
    if ! docker compose exec -T ollama ollama pull llama3.2; then
        echo "  [NOTE] External Ollama download skipped or rate-limited. Fallback deterministic reasoner active."
    fi
fi

echo "=========================================================================="
echo "          FaceCheck Local Stack Successfully Initialized!"
echo "=========================================================================="
echo "  * REST API (FastAPI):          http://127.0.0.1:8000/docs"
echo "  * Read-Only Monitor Web:       http://127.0.0.1:8080"
echo "  * Ollama Local LLM:            http://127.0.0.1:11434"
echo "  * API Key (X-API-Key):         $(grep '^FACECHECK_API_KEY=' "${ENV_FILE}" | cut -d= -f2-)"
echo ""
echo "Next steps:"
echo "  - Run full test suite in Docker:   scripts/test.sh"
echo "  - View live logs:                  scripts/logs.sh"
echo "  - Stop the stack:                  scripts/stop.sh"
echo "=========================================================================="
